package libraryManagement;

public class Books {
	int bookid;
	String title;
	String author;
	String category;
	float price;
	public Books(int bookid, String title, String author, String category, float price) {
		super();
		this.bookid = bookid;
		this.title = title;
		this.author = author;
		this.category = category;
		this.price = price;
	}
}
